/**
 * Vault document classes (user_boilerplate_docs.doc_class — migration
 * 20261117_vault_doc_class.sql).
 *
 *   company   — the user's own company material. The ONLY class the parse → commit
 *               flow turns into Vault facts (identity, past performance, capabilities).
 *   reference — a file attached in Ask Mindy to ask about (an RFP, a SOW, a competitor's
 *               brochure). Facts in it are NOT the user's facts.
 *   generated — a file Mindy rendered. Its contents came from Mindy, not the user.
 *
 * NULL is a legacy row written before the column existed, and every one of those came
 * from the Vault upload screen, so NULL means 'company'. No backfill is needed.
 */

export const DOC_CLASSES = ['company', 'reference', 'generated'] as const;
export type DocClass = (typeof DOC_CLASSES)[number];

export function effectiveDocClass(row: { doc_class?: unknown } | null | undefined): DocClass {
  const v = row?.doc_class;
  return v === 'reference' || v === 'generated' ? v : 'company';
}

/**
 * May this document's parsed contents be written into the user's Vault facts?
 * Company documents: yes (the review modal is already the user's confirmation).
 * Reference and generated documents: only with an explicit, separate confirmation
 * that the user is asserting these facts as their own.
 */
export function mayCommitToFacts(
  row: { doc_class?: unknown } | null | undefined,
  confirmedNonCompany: boolean,
): { ok: true } | { ok: false; docClass: DocClass; message: string } {
  const docClass = effectiveDocClass(row);
  if (docClass === 'company' || confirmedNonCompany === true) return { ok: true };
  return {
    ok: false,
    docClass,
    message:
      docClass === 'reference'
        ? "This file was attached in Ask Mindy as a reference document, not as your company's material. Confirm that these details describe your own company before saving them to your Vault."
        : 'This file was generated by Mindy. Confirm that these details describe your own company before saving them to your Vault.',
  };
}
