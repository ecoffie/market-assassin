/** Build the membership key the same way the build script does. */
export function repeatBuyerKey(agencyKey: string, naics: string): string {
  return `${agencyKey}|${naics}`;
}

/**
 * Is this agency a repeat buyer of this NAICS? Grounded membership check — false when either input is
 * missing, when the agency doesn't normalize, or when the pair isn't in the precomputed qualifying set.
 */
export function isRepeatBuyer(agency: string | null | undefined, naics: string | null | undefined): boolean {
  const nc = (naics || '').trim();
  if (!nc) return false;
  const key = normalizeAgencyKey(agency || '');
  if (!key) return false;
  return REPEAT_BUYER_PAIRS.has(repeatBuyerKey(key, nc));
}
