/**
 * Repeat-buyer classification — the "this agency actually buys THIS work repeatedly" DNA strand.
 *
 * Grounds the Opportunity DNA "Repeat Buyer" strand (Phase 1.5). The signal: a buying agency has
 * awarded ≥ REPEAT_BUYER_MIN real contracts in a given NAICS — a genuine, repeated buying pattern,
 * not a one-off. Measured from `recompete_opportunities` (quality_flag IS NULL — real per-contract
 * rows), grouped by (normalizeAgencyKey(awarding_agency|awarding_sub_agency), naics_code).
 *
 * Why a PRECOMPUTED SET, not a per-pin query: `computeBuyerBehavior` grounds the same idea but costs
 * ~6 Supabase round-trips PER call (detail-only). The map decorates ~400 pins/viewport, so a per-pin
 * query is ~2,400 round-trips — not viable. Instead this is a one-time classification stored as a
 * constant (exactly the `sap-friendly-agencies.ts` pattern), so the map does a cheap MEMBERSHIP check:
 * `REPEAT_BUYER_PAIRS.has(normalizeAgencyKey(agency) + '|' + naics)`. Re-derive with
 * `scripts/build-repeat-buyer-map.ts` when the award data materially shifts.
 *
 * NO FABRICATION: only pairs that CLEARED the ≥ REPEAT_BUYER_MIN floor are in the set. An agency×NAICS
 * absent from the set → NOT a repeat buyer (honest: either genuinely rare, or below the floor). A pin
 * with no NAICS or no agency → never a repeat buyer (the lookup returns false).
 */
