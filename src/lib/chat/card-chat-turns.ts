/**
 * Card chat: charge once per question (approved by Eric 2026-11-14).
 *
 * One successfully completed AND durably saved answer = one charge. The browser gives each submitted
 * question a stable turn id and reuses it on retry, refresh and reopen. The database functions in
 * supabase/migrations/20261114_card_chat_turns.sql are the only gate:
 *   - claimCardTurn     first request owns the turn; a duplicate sees 'in_progress'; a completed turn returns
 *                       its saved answer (no model call, no debit); a failed turn can be claimed again.
 *   - completeCardTurn  saves the answer + sources AND debits through mcp_debit_credits in ONE transaction,
 *                       so an answer is never charged without being recoverable by its owner.
 *   - failCardTurn      a failed / empty / degraded / incomplete answer is free and re-claimable.
 * Every function throws on a database error: the caller treats that as UNKNOWN and never charges.
 */
import { createClient, type SupabaseClient } from '@supabase/supabase-js';

/** A turn id is a v4-shaped uuid generated by the browser. */
const TURN_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * How long one request owns a turn. Longer than the slowest card answer (planner + tools + streamed answer),
 * so a live request is never displaced; if the request dies, the turn becomes claimable again after this.
 */
export const CARD_TURN_LEASE_SECONDS = 300;

export function parseTurnId(raw: unknown): string | null {
  const s = typeof raw === 'string' ? raw.trim().toLowerCase() : '';
  return TURN_ID.test(s) ? s : null;
}

export type CitedSourceRow = { title: string; url: string | null; doc_type: string; source_path: string | null; document_id: string | null };

export type ClaimResult =
  | { outcome: 'claimed'; claimToken: string; sessionId: string | null }
  | { outcome: 'completed'; answer: string; citedSources: CitedSourceRow[]; sessionId: string | null; creditsCharged: number }
  | { outcome: 'in_progress' | 'mismatch' | 'not_completed'; sessionId: string | null };

export type CompleteResult = {
  outcome: 'charged' | 'not_billable' | 'insufficient_balance' | 'already_completed' | 'lost_claim' | 'not_found';
  creditsCharged: number;
  newBalance: number | null;
};

let _client: SupabaseClient | null = null;
function db(): SupabaseClient {
  if (!_client) _client = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!);
  return _client;
}

function firstRow<T>(data: unknown): T | null {
  return (Array.isArray(data) ? data[0] : data) as T | null;
}

export async function claimCardTurn(p: {
  turnId: string; email: string; noticeId: string; sessionId: string | null; question: string; replayOnly: boolean;
}): Promise<ClaimResult> {
  const { data, error } = await db().rpc('card_chat_claim_turn', {
    p_turn: p.turnId, p_user: p.email.toLowerCase(), p_notice: p.noticeId, p_session: p.sessionId,
    p_question: p.question, p_lease_seconds: CARD_TURN_LEASE_SECONDS, p_replay_only: p.replayOnly,
  });
  if (error) throw new Error(`card_chat_claim_turn failed: ${error.message}`);
  const row = firstRow<{ outcome: string; claim_token: string | null; answer: string | null; cited_sources: unknown; session_id: string | null; credits_charged: number | null }>(data);
  if (!row?.outcome) throw new Error('card_chat_claim_turn returned no row');
  if (row.outcome === 'claimed') {
    if (!row.claim_token) throw new Error('card_chat_claim_turn: claimed without a token');
    return { outcome: 'claimed', claimToken: row.claim_token, sessionId: row.session_id };
  }
  if (row.outcome === 'completed') {
    return {
      outcome: 'completed', answer: String(row.answer || ''), sessionId: row.session_id,
      citedSources: Array.isArray(row.cited_sources) ? (row.cited_sources as CitedSourceRow[]) : [],
      creditsCharged: Number(row.credits_charged || 0),
    };
  }
  if (row.outcome === 'in_progress' || row.outcome === 'mismatch' || row.outcome === 'not_completed') {
    return { outcome: row.outcome, sessionId: row.session_id };
  }
  throw new Error(`card_chat_claim_turn: unexpected outcome ${row.outcome}`);
}

export async function completeCardTurn(p: {
  turnId: string; claimToken: string; email: string; answer: string; citedSources: CitedSourceRow[]; sessionId: string; credits: number;
}): Promise<CompleteResult> {
  const { data, error } = await db().rpc('card_chat_complete_turn', {
    p_turn: p.turnId, p_token: p.claimToken, p_user: p.email.toLowerCase(), p_answer: p.answer,
    p_sources: p.citedSources, p_session: p.sessionId, p_credits: Math.max(0, Math.floor(p.credits)),
  });
  if (error) throw new Error(`card_chat_complete_turn failed: ${error.message}`);
  const row = firstRow<{ outcome: CompleteResult['outcome']; credits_charged: number | null; new_balance: number | null }>(data);
  if (!row?.outcome) throw new Error('card_chat_complete_turn returned no row');
  return { outcome: row.outcome, creditsCharged: Number(row.credits_charged || 0), newBalance: row.new_balance == null ? null : Number(row.new_balance) };
}

export async function failCardTurn(p: { turnId: string; claimToken: string; reason: string }): Promise<void> {
  const { error } = await db().rpc('card_chat_fail_turn', { p_turn: p.turnId, p_token: p.claimToken, p_reason: p.reason });
  if (error) throw new Error(`card_chat_fail_turn failed: ${error.message}`);
}
