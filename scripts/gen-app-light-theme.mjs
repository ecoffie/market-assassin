import fs from 'node:fs';
const theme = fs.readFileSync('node_modules/tailwindcss/theme.css','utf8');
const tw = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (tw[m[1]] ||= {})[m[2]] = m[3].trim();
const steps = ['50','100','200','300','400','500','600','700','800','900','950'];
const out = [];
out.push(`/* GENERATED by scripts/gen-app-light-theme.mjs — do not hand-edit.
   Light ("homepage + map") look for the signed-in app. Everything is scoped to
   .mi-light, which only the /app tree carries, so admin/other dark pages are
   unchanged. Tailwind v4 compiles palette utilities to var(--color-*), so
   redefining the vars here re-colors the existing classes without touching
   ~4,000 class names. */`);
const L = [];
// Semantic tokens
Object.entries({
  ground:'#f6f8fb','ground-deep':'#eef1f5',surface:'#ffffff','surface-2':'#f3f5f8',input:'#eef1f5',hairline:'#e3e7ec',
  ink:'#12100e','ink-soft':'#3f4650',muted:'#5b6470',faint:'#6b7280',
  navy:'#1b3a6b','navy-hover':'#14294a',accent:'#1b3a6b','accent-hover':'#14294a',
  ok:'#12805c',warn:'#b45309',crit:'#b4231a',info:'#0369a1',
  'navy-950':'#eef1f5','navy-900':'#f6f8fb','navy-800':'#ffffff','navy-700':'#e3e7ec','navy-600':'#cfd5dc',
  'accent-blue':'#1d4ed8','accent-cyan':'#0e7490','accent-emerald':'#12805c','accent-amber':'#b45309',
}).forEach(([k,v])=>L.push(`--color-${k}:${v}`));
L.push('--shadow-raised:0 1px 2px 0 rgb(16 24 40 / .06),0 1px 3px 0 rgb(16 24 40 / .08)');
L.push('--shadow-overlay:0 4px 12px -2px rgb(16 24 40 / .12),0 2px 6px -2px rgb(16 24 40 / .08)');
L.push('--shadow-modal:0 16px 40px -8px rgb(16 24 40 / .22),0 6px 16px -6px rgb(16 24 40 / .12)');
L.push('--background:#f6f8fb','--background-dark:#eef1f5','--card-bg:#ffffff','--card-border:#e3e7ec','--foreground:#12100e','--text-primary:#12100e','--text-secondary:#5b6470','--text-muted:#6b7280');
// white = ink (text-white is the dark UI's primary text); black stays for scrims
L.push('--color-white:#12100e');
// neutrals inverted
const NEU = {950:'#eef1f5',900:'#f6f8fb',800:'#ffffff',700:'#e3e7ec',600:'#cfd5dc',500:'#6b7280',400:'#5b6470',300:'#3f4650',200:'#2a2f36',100:'#12100e',50:'#0b0d10'};
for (const h of ['slate','gray','zinc','neutral','stone']) for (const s of steps) L.push(`--color-${h}-${s}:${NEU[s]}`);
// brand purples -> navy
const NAVY = {50:'#14294a',100:'#14294a',200:'#1b3a6b',300:'#1b3a6b',400:'#1b3a6b',500:'#1b3a6b',600:'#1b3a6b',700:'#14294a',800:'#dfe6f0',900:'#e8edf5',950:'#f1f4f9'};
for (const h of ['purple','violet','indigo']) for (const s of steps) L.push(`--color-${h}-${s}:${NAVY[s]}`);
// colored hues: light text steps darken, dark bg steps become washes
const MAP = {50:'900',100:'800',200:'800',300:'700',400:'700',500:'600',600:'600',700:'700',800:'200',900:'100',950:'50'};
const HUES = ['blue','sky','cyan','teal','emerald','green','lime','yellow','amber','orange','red','rose','pink','fuchsia'];
for (const h of HUES) for (const s of steps) if (tw[h]?.[MAP[s]]) L.push(`--color-${h}-${s}:${tw[h][MAP[s]]}`);
out.push(`.mi-light{${L.join(';')};color-scheme:light;background:#f6f8fb;color:#12100e}`);
// Strong fills keep real white text: re-scope --color-white on them (and children).
const strong = [];
const word = (c)=>[`[class^="${c}"]`,`[class*=" ${c}"]`];
for (const h of [...HUES,'purple','violet','indigo']) for (const s of ['500','600','700']) { strong.push(...word(`bg-${h}-${s}`), ...word(`from-${h}-${s}`)); }
for (const t of ['bg-navy','bg-accent','bg-ok','bg-crit','bg-black','from-navy','from-accent','from-[#1e3a8a]','bg-[#1e3a8a]','bg-[#7c3aed]']) strong.push(...word(t));
out.push(`.mi-light :is(${strong.join(',')}){--color-white:#ffffff}`);
// translucent tints of a strong hue (bg-blue-600/20) are NOT strong — put ink back
const tint = [];
for (const h of [...HUES,'purple','violet','indigo']) for (const s of ['500','600','700']) tint.push(...word(`bg-${h}-${s}/`));
out.push(`.mi-light :is(${tint.join(',')}){--color-white:#12100e}`);
// bg-white in the dark UI = a light chip/button with dark text: keep it white with ink text
out.push(`.mi-light :is([class^="bg-white "],[class*=" bg-white "],[class$=" bg-white"],[class="bg-white"]){background-color:#ffffff;border:1px solid #e3e7ec;--color-slate-900:#12100e;--color-gray-900:#12100e;--color-slate-800:#1f2937;--color-gray-800:#1f2937;--color-slate-700:#374151;--color-gray-700:#374151;--color-slate-600:#4b5563;--color-gray-600:#4b5563}`);
// Page titles: serif like the homepage
out.push(`.mi-light :is(h1,.text-page){font-family:"Libre Baskerville",Georgia,serif;font-weight:400;letter-spacing:-.01em}`);
out.push(`.mi-light ::selection{background:#c9d6e8;color:#12100e}`);
out.push(`html.mi-light,html.mi-light body{background:#f6f8fb;color:#12100e;color-scheme:light}`);
out.push(`html.mi-light ::-webkit-scrollbar-track{background:#eef1f5}html.mi-light ::-webkit-scrollbar-thumb{background:#cfd5dc}`);
process.stdout.write(out.join('\n')+'\n');
